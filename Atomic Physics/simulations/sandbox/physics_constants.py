import scipy.constants as sc

# Constantes Físicas Universales (SI)
C = sc.c              # Velocidad de la luz [m/s]
H = sc.h              # Constante de Planck [J*s]
HBAR = sc.hbar        # Constante de Planck reducida [J*s]
KB = sc.k              # Constante de Boltzmann [J/K]
EPSILON_0 = sc.epsilon_0 # Permitividad del vacío [F/m]
MU_0 = sc.mu_0        # Permeabilidad del vacío [N/A^2]
E = sc.e              # Carga elemental [C]
U = sc.u              # Unidad de masa atómica unificada [kg]

MHZ_TO_RAD = 2 * sc.pi * 1e6  # Para pasar de MHz a rad/s